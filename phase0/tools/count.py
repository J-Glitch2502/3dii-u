#!/usr/bin/env python3
"""Runs the ARM workload in Unicorn to get each kernel's exact instruction counts and reference results.
count.py <code.bin> <counts.h>. Count = base + per_iter * iters, measured from iters 2 and 4."""
import sys

from unicorn import UC_ARCH_ARM, UC_HOOK_CODE, UC_MODE_ARM, Uc
from unicorn.arm_const import (UC_ARM_REG_C1_C0_2, UC_ARM_REG_FPEXC, UC_ARM_REG_LR, UC_ARM_REG_R0, UC_ARM_REG_R1,
                               UC_ARM_REG_SP, UC_CPU_ARM_1176)

BASE, STACK_TOP, EXIT = 0x00100000, 0x0FF00000, 0xFFFF0000
NAMES = ['entities', 'math', 'bytes', 'sort', 'calls', 'mix', 'unaligned']

code = open(sys.argv[1], 'rb').read()
uc = Uc(UC_ARCH_ARM, UC_MODE_ARM)
uc.ctl_set_cpu_model(UC_CPU_ARM_1176)
uc.mem_map(BASE, 0x100000)
uc.mem_map(STACK_TOP - 0x100000, 0x100000)
uc.mem_map(EXIT, 0x1000)
uc.mem_write(BASE, code)
uc.reg_write(UC_ARM_REG_C1_C0_2, uc.reg_read(UC_ARM_REG_C1_C0_2) | (0xF << 20))  # VFP access on
uc.reg_write(UC_ARM_REG_FPEXC, 0x40000000)

count = 0


def tick(*_):
    global count
    count += 1


uc.hook_add(UC_HOOK_CODE, tick)


def run(kernel, iters):
    global count
    count = 0
    uc.reg_write(UC_ARM_REG_R0, kernel)
    uc.reg_write(UC_ARM_REG_R1, iters)
    uc.reg_write(UC_ARM_REG_SP, STACK_TOP)
    uc.reg_write(UC_ARM_REG_LR, EXIT)
    uc.emu_start(BASE, EXIT)
    return count, uc.reg_read(UC_ARM_REG_R0)


rows = []
for k, name in enumerate(NAMES):
    _, r1 = run(k, 1)
    c2, r2 = run(k, 2)
    c4, _ = run(k, 4)  # 'calls' alternates its depth, so measure over a whole cycle
    per_iter = (c4 - c2) // 2
    assert per_iter > 0, name
    rows.append((name, c2 - 2 * per_iter, per_iter, r1, r2))
    print(f'{name:10} base {c2 - 2 * per_iter:>8} per_iter {per_iter:>8} check {r1:08x} {r2:08x}')

with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/count.py from the ARM workload.\n#pragma once\n')
    f.write('static const struct { const char *name; unsigned base, per_iter, check[2]; } kernel_counts[] = {\n')
    for name, base, per_iter, r1, r2 in rows:
        f.write(f'    {{"{name}", {max(base, 0)}u, {per_iter}u, {{0x{r1:08x}u, 0x{r2:08x}u}}}},\n')
    f.write('};\n')
